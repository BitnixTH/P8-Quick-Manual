/* =========================================================
   GO TO STEP
========================================================= */

function goToStep(index) {

  if (
    index < 0 ||
    index >= steps.length
  ) {
    return;
  }


  activeStepIndex =
    index;


  openStepIndex =
    index;


  openOnlyStep(
    index
  );


  updateJourneyProgress(
    index
  );


  const card =
    document.getElementById(
      steps[index].id
    );


  if (!card) return;


  setTimeout(
    () => {

      const top =
        card
          .getBoundingClientRect()
          .top
        +
        window.scrollY
        -
        118;


      window.scrollTo({

        top,

        behavior:
          "smooth"

      });

    },
    100
  );

}


/* =========================================================
   OPEN ONE CARD ONLY
========================================================= */

function openOnlyStep(index) {

  const cards =
    Array.from(
      document.querySelectorAll(
        ".step-card"
      )
    );


  cards.forEach(
    (
      card,
      cardIndex
    ) => {

      const content =
        card.querySelector(
          ".step-content"
        );


      const shouldOpen =
        cardIndex === index;


      card.classList.toggle(
        "open",
        shouldOpen
      );


      updateCardToggle(
        card,
        shouldOpen
      );


      if (shouldOpen) {

        openStepIndex =
          index;


        content.style.maxHeight =
          content.scrollHeight +
          "px";


        setTimeout(
          () => {

            content.style.maxHeight =
              content.scrollHeight +
              "px";

          },
          100
        );


      } else {

        content.style.maxHeight =
          null;

      }

    }
  );

}


