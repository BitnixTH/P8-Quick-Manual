/* =========================================================
   SIDEBAR EVENT
========================================================= */

function bindSidebarButtons() {

  const buttons =
    document.querySelectorAll(
      ".side-button"
    );


  buttons.forEach(
    (button) => {

      button.addEventListener(
        "click",
        () => {

          const index =
            Number(
              button.dataset
                .stepIndex
            );


          goToStep(
            index
          );

        }
      );

    }
  );

}


