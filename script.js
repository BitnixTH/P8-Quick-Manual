/* =========================================================
   MANUAL CONTENT SCROLL
   BIT TELEMEDICINE STYLE
========================================================= */

function setupSliders() {

  document
    .querySelectorAll(
      "[data-slider]"
    )
    .forEach(
      (slider) => {

        const card =
          slider.closest(
            ".step-card"
          );


        const viewport =
          slider.querySelector(
            ".slider-viewport"
          );


        const track =
          slider.querySelector(
            ".slider-track"
          );


        const slides =
          Array.from(
            slider.querySelectorAll(
              ".slide"
            )
          );


        const previousButton =
          slider.querySelector(
            ".slider-button.prev"
          );


        const nextButton =
          slider.querySelector(
            ".slider-button.next"
          );


        const dotsContainer =
          slider.querySelector(
            ".slider-dots"
          );


        const currentLabel =
          slider.querySelector(
            ".current-slide"
          );


        const totalLabel =
          slider.querySelector(
            ".total-slides"
          );


        const subnavButtons =
          Array.from(
            card.querySelectorAll(
              ".subnav-btn"
            )
          );


        let currentIndex = 0;


        /* ===================================================
           DOTS
        =================================================== */

        dotsContainer.innerHTML = "";


        slides.forEach(
          (slide, index) => {

            const dot =
              document.createElement(
                "button"
              );


            dot.type = "button";
            dot.className = "slider-dot";


            dot.addEventListener(
              "click",
              () => {

                currentIndex = index;

                showSlide();

              }
            );


            dotsContainer.appendChild(
              dot
            );

          }
        );


        const dots =
          Array.from(
            dotsContainer.querySelectorAll(
              ".slider-dot"
            )
          );


        totalLabel.textContent =
          slides.length;


        /* ===================================================
           ACTIVE CONTENT
        =================================================== */

        function getActiveSlide() {

          return slides[currentIndex];

        }


        function getActiveScrollBox() {

          return getActiveSlide()
            ?.querySelector(
              ".slide-scroll"
            );

        }


        /* ===================================================
           UPDATE REAL CONTENT SCROLLBAR
        =================================================== */

        function updateContentScrollbar() {

          const slide =
            getActiveSlide();


          if (!slide) {
            return;
          }


          const scrollBox =
            slide.querySelector(
              ".slide-scroll"
            );


          const scrollbar =
  slider.querySelector(
    ".content-scrollbar"
  );


const scrollbarTrack =
  slider.querySelector(
    ".content-scrollbar-track"
  );


const scrollbarThumb =
  slider.querySelector(
    ".content-scrollbar-thumb"
  );


          if (
            !scrollBox ||
            !scrollbar ||
            !scrollbarTrack ||
            !scrollbarThumb
          ) {
            return;
          }


          const visibleHeight =
            scrollBox.clientHeight;


          const fullHeight =
            scrollBox.scrollHeight;


          const trackHeight =
            scrollbarTrack.clientHeight;


          if (
            visibleHeight <= 0 ||
            fullHeight <= 0 ||
            trackHeight <= 0
          ) {
            return;
          }


          const visibleRatio =
            Math.min(
              1,
              visibleHeight / fullHeight
            );


          const thumbHeight =
            Math.max(
              72,
              trackHeight * visibleRatio
            );


          scrollbarThumb.style.height =
            `${Math.min(
              thumbHeight,
              trackHeight
            )}px`;


          const maxScroll =
            Math.max(
              0,
              fullHeight - visibleHeight
            );


          const maxThumbTop =
            Math.max(
              0,
              trackHeight -
              scrollbarThumb.offsetHeight
            );


          const scrollRatio =
            maxScroll === 0
              ? 0
              : scrollBox.scrollTop /
                maxScroll;


          const thumbTop =
            scrollRatio *
            maxThumbTop;


          scrollbarThumb.style.transform =
            `translateX(-50%) translateY(${thumbTop}px)`;


          scrollbar.classList.toggle(
            "no-scroll",
            maxScroll <= 1
          );


          /* ▲ disabled when at top */

          previousButton.disabled =
            scrollBox.scrollTop <= 1;


          /* ▼ disabled when at bottom */

          nextButton.disabled =
            scrollBox.scrollTop +
              scrollBox.clientHeight
            >=
            scrollBox.scrollHeight - 1;

        }


        /* ===================================================
           BIND SCROLLBAR TO EACH TOPIC
        =================================================== */

        function bindRealScrollbar(
          slide
        ) {

          const scrollBox =
            slide.querySelector(
              ".slide-scroll"
            );


          const scrollbarTrack =
  slider.querySelector(
    ".content-scrollbar-track"
  );


const scrollbarThumb =
  slider.querySelector(
    ".content-scrollbar-thumb"
  );

          if (
            !scrollBox ||
            !scrollbarTrack ||
            !scrollbarThumb
          ) {
            return;
          }


          /* Track normal mouse / touch scrolling */

          scrollBox.addEventListener(
            "scroll",
            () => {

              if (
                slide ===
                getActiveSlide()
              ) {

                updateContentScrollbar();

              }

            },
            {
              passive: true
            }
          );


          /* Click scrollbar track */

          scrollbarTrack.addEventListener(
            "pointerdown",
            (event) => {

              if (
                event.target ===
                scrollbarThumb
              ) {
                return;
              }


              event.preventDefault();


              const rect =
                scrollbarTrack
                  .getBoundingClientRect();


              const ratio =
                Math.max(
                  0,
                  Math.min(
                    1,
                    (
                      event.clientY -
                      rect.top
                    ) /
                    rect.height
                  )
                );


              const maxScroll =
                Math.max(
                  0,
                  scrollBox.scrollHeight -
                  scrollBox.clientHeight
                );


              scrollBox.scrollTo({

                top:
                  maxScroll * ratio,

                behavior:
                  "smooth"

              });

            }
          );


          /* Drag scrollbar thumb */

          scrollbarThumb.addEventListener(
            "pointerdown",
            (event) => {

              event.preventDefault();


              const startY =
                event.clientY;


              const startScroll =
                scrollBox.scrollTop;


              const maxScroll =
                Math.max(
                  0,
                  scrollBox.scrollHeight -
                  scrollBox.clientHeight
                );


              const maxThumbTravel =
                Math.max(
                  1,
                  scrollbarTrack.clientHeight -
                  scrollbarThumb.offsetHeight
                );


              scrollbarThumb.classList.add(
                "dragging"
              );


              function onMove(
                moveEvent
              ) {

                const deltaY =
                  moveEvent.clientY -
                  startY;


                const scrollDelta =
                  (
                    deltaY /
                    maxThumbTravel
                  ) *
                  maxScroll;


                scrollBox.scrollTop =
                  startScroll +
                  scrollDelta;

              }


              function onEnd() {

                scrollbarThumb.classList.remove(
                  "dragging"
                );


                document.removeEventListener(
                  "pointermove",
                  onMove
                );


                document.removeEventListener(
                  "pointerup",
                  onEnd
                );


                document.removeEventListener(
                  "pointercancel",
                  onEnd
                );

              }


              document.addEventListener(
                "pointermove",
                onMove
              );


              document.addEventListener(
                "pointerup",
                onEnd
              );


              document.addEventListener(
                "pointercancel",
                onEnd
              );

            }
          );

        }


        slides.forEach(
          bindRealScrollbar
        );


        /* ===================================================
           CHANGE TOPIC / IMAGE GROUP
        =================================================== */

        function showSlide() {

          const height =
            viewport.clientHeight;


          track.style.transform =
            `translateY(-${currentIndex * height}px)`;


          slides.forEach(
            (slide, index) => {

              slide.classList.toggle(
                "active",
                index === currentIndex
              );

            }
          );


          dots.forEach(
            (dot, index) => {

              dot.classList.toggle(
                "active",
                index === currentIndex
              );

            }
          );


          subnavButtons.forEach(
            (button) => {

              const target =
                Number(
                  button.dataset
                    .slideTarget
                );


              button.classList.toggle(
                "active",
                target === currentIndex
              );

            }
          );


          currentLabel.textContent =
            currentIndex + 1;


          /*
            When changing topic,
            start content from the top.
          */

          const scrollBox =
            getActiveScrollBox();


          if (scrollBox) {

            scrollBox.scrollTop = 0;

          }


          requestAnimationFrame(
            () => {

              updateContentScrollbar();

              updateOpenCardHeight();

            }
          );

        }


        /* ===================================================
           ▲ SCROLL CONTENT UP
        =================================================== */

        previousButton.addEventListener(
          "click",
          (event) => {

            event.stopPropagation();


            const scrollBox =
              getActiveScrollBox();


            if (!scrollBox) {
              return;
            }


            scrollBox.scrollBy({

              top:
                -Math.max(
                  180,
                  scrollBox.clientHeight *
                  0.70
                ),

              behavior:
                "smooth"

            });

          }
        );


        /* ===================================================
           ▼ SCROLL CONTENT DOWN
        =================================================== */

        nextButton.addEventListener(
          "click",
          (event) => {

            event.stopPropagation();


            const scrollBox =
              getActiveScrollBox();


            if (!scrollBox) {
              return;
            }


            scrollBox.scrollBy({

              top:
                Math.max(
                  180,
                  scrollBox.clientHeight *
                  0.70
                ),

              behavior:
                "smooth"

            });

          }
        );


        /* ===================================================
           TOP SUBNAV BUTTONS
        =================================================== */

        subnavButtons.forEach(
          (button) => {

            button.addEventListener(
              "click",
              (event) => {

                event.stopPropagation();


                const target =
                  Number(
                    button.dataset
                      .slideTarget
                  );


                if (
                  target < 0 ||
                  target >= slides.length
                ) {
                  return;
                }


                currentIndex = target;

                showSlide();

              }
            );

          }
        );


        /* ===================================================
           RESIZE
        =================================================== */

        window.addEventListener(
          "resize",
          () => {

            showSlide();

          }
        );


        /* Initial state */

        showSlide();

      }
    );

}

/* =========================================================
   MISSING IMAGE HANDLING
   MULTIPLE IMAGES PER TOPIC
========================================================= */

function setupMissingImages() {

  const slides =
    Array.from(
      document.querySelectorAll(
        ".slide"
      )
    );


  slides.forEach(
    (slide) => {

      const images =
        Array.from(
          slide.querySelectorAll(
            ".slide-image"
          )
        );


      const placeholder =
        slide.querySelector(
          ".slide-placeholder"
        );


      const scrollBox =
        slide.querySelector(
          ".slide-scroll"
        );


      if (
        !placeholder ||
        !scrollBox
      ) {
        return;
      }


      /*
        Check whether at least one image
        inside this topic is available.
      */

      function updateSlideState() {

        const validImages =
          images.filter(
            (image) =>
              image.dataset
                .imageStatus === "loaded"
          );


        if (
          validImages.length > 0
        ) {

          /*
            At least one real image exists.
            Show real content.
          */

          placeholder.style.display =
            "none";


          slide.classList.remove(
            "missing-image"
          );


        } else {

          /*
            No image in this topic
            loaded successfully.
            Show placeholder.
          */

          placeholder.style.display =
            "flex";


          slide.classList.add(
            "missing-image"
          );

        }


        /*
          Image loading changes scrollHeight.
          Trigger the scroll handler so the
          real scrollbar recalculates itself.
        */

        requestAnimationFrame(
          () => {

            scrollBox.dispatchEvent(
              new Event("scroll")
            );


            updateOpenCardHeight();

          }
        );

      }


      /*
        No image assigned to this topic.
      */

      if (
        images.length === 0
      ) {

        placeholder.style.display =
          "flex";


        slide.classList.add(
          "missing-image"
        );


        return;

      }


      images.forEach(
        (image) => {

          image.addEventListener(
            "load",
            () => {

              image.dataset.imageStatus =
                "loaded";


              image.style.display =
                "block";


              updateSlideState();

            }
          );


          image.addEventListener(
            "error",
            () => {

              /*
                Only hide this broken image.
                Do NOT hide the whole topic.
              */

              image.dataset.imageStatus =
                "error";


              image.style.display =
                "none";


              updateSlideState();

            }
          );


          /*
            Handle images that already
            finished loading before the
            listeners were attached.
          */

          if (
            image.complete
          ) {

            if (
              image.naturalWidth > 0
            ) {

              image.dataset.imageStatus =
                "loaded";


              image.style.display =
                "block";


            } else {

              image.dataset.imageStatus =
                "error";


              image.style.display =
                "none";

            }

          }

        }
      );


      /*
        Initial state.
        If some images are still loading,
        wait for their load/error events.
      */

      const finishedImages =
        images.filter(
          (image) =>
            image.dataset.imageStatus
        );


      if (
        finishedImages.length ===
        images.length
      ) {

        updateSlideState();

      }

    }
  );

}

/* =========================================================
   BEFORE IMAGE FALLBACK
========================================================= */

function setupBeforeImageFallback() {

  const image =
    document.getElementById(
      "journeyStartImage"
    );


  if (!image) {
    return;
  }


  const candidates = [

    "Image/Before 1.png",

    "Image/Before1.png",

    "Image/Before-1.png",

    "Image/Before.png"

  ];


  let currentCandidate =
    0;


  image.addEventListener(
    "error",
    () => {

      currentCandidate++;


      if (
        currentCandidate <
        candidates.length
      ) {

        image.src =
          candidates[
            currentCandidate
          ];

      } else {

        image.style.display =
          "none";

      }

    }
  );

}


