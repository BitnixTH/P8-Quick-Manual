function setLanguage(language) {

  currentLanguage =
    language;


  document
    .querySelectorAll(
      "[data-th][data-en]"
    )
    .forEach(
      (element) => {

        const text =
          element.dataset[
            language
          ];


        if (
          text !== undefined
        ) {

          element.innerHTML =
            text.replace(
              /\|/g,
              "<br>"
            );

        }

      }
    );


  languageButtons.forEach(
    (button) => {

      button.classList.toggle(
        "active",
        button.dataset.lang ===
          language
      );

    }
  );


  document.documentElement.lang =
    language === "th"
      ? "th"
      : "en";


  buildSidebar();


  buildManual();


  /*
    If the patient already opened
    a card, preserve that open card
    after switching language.

    If no card is open,
    keep every card collapsed.
  */

  if (
    openStepIndex !== null
  ) {

    openOnlyStep(
      openStepIndex
    );

  }


  updateJourneyProgress(
    activeStepIndex
  );


  updateOpenCardHeight();

}


